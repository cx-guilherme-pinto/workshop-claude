#!/usr/bin/env node
// Gera os ficheiros que contem URLs a partir do repos.conf (+ variaveis de ambiente com o mesmo nome):
// O ingles e a versao principal (D-21): docs/ e README.md em ingles, docs/pt/ e README.pt.md em portugues,
// e o README e o guia de instalacao tambem em hindi e hebraico.
//   tools/templates/en/*.tmpl  -> README.md, docs/PUBLISHING.md, docs/INSTALL.md, docs/EMAIL.md
//   tools/templates/pt/*.tmpl  -> README.pt.md, docs/pt/PUBLISHING.md, docs/pt/INSTALL.md, docs/pt/EMAIL.md
//   tools/templates/hi/*.tmpl  -> README.hi.md, docs/hi/INSTALL.md
//   tools/templates/he/*.tmpl  -> README.he.md, docs/he/INSTALL.md
//   setup/messages.en.json     -> docs/TROUBLESHOOTING.md (catalogo de erros, por sistema operativo)
//   setup/messages.pt.json     -> docs/pt/TROUBLESHOOTING.md
// e escreve a lista dos ficheiros gerados em tools/generated-files.json (usada pelo tools/check-repo.mjs).
//
//   node tools/render.mjs            gera
//   node tools/render.mjs --check    so confirma que os ficheiros gerados estao atualizados (CI)
//   node tools/render.mjs --vars     mostra os valores disponiveis para os templates
//
// Marcadores nos templates: {{NOME}} (ex.: {{ONE_LINER_MAC}}, {{RELEASE_URL}}, {{SHA256SUMS_URL}}).
// Um marcador desconhecido e um erro.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { KIT_ROOT, derived, loadConf } from '../installer/lib/conf.mjs';
import { loadMessages, renderTroubleshooting } from '../installer/lib/messages.mjs';

// [template, destino, lingua]
export const TEMPLATES = [
  ['tools/templates/en/README.md.tmpl', 'README.md', 'en'],
  ['tools/templates/en/PUBLISHING.md.tmpl', 'docs/PUBLISHING.md', 'en'],
  ['tools/templates/en/INSTALL.md.tmpl', 'docs/INSTALL.md', 'en'],
  ['tools/templates/en/EMAIL.md.tmpl', 'docs/EMAIL.md', 'en'],
  ['tools/templates/pt/README.md.tmpl', 'README.pt.md', 'pt'],
  ['tools/templates/pt/PUBLISHING.md.tmpl', 'docs/pt/PUBLISHING.md', 'pt'],
  ['tools/templates/pt/INSTALL.md.tmpl', 'docs/pt/INSTALL.md', 'pt'],
  ['tools/templates/pt/EMAIL.md.tmpl', 'docs/pt/EMAIL.md', 'pt'],
  ['tools/templates/hi/README.md.tmpl', 'README.hi.md', 'hi'],
  ['tools/templates/hi/INSTALL.md.tmpl', 'docs/hi/INSTALL.md', 'hi'],
  ['tools/templates/he/README.md.tmpl', 'README.he.md', 'he'],
  ['tools/templates/he/INSTALL.md.tmpl', 'docs/he/INSTALL.md', 'he'],
];
// docs/TROUBLESHOOTING.md (en) e docs/pt/TROUBLESHOOTING.md (pt), gerados do catalogo de mensagens dessa lingua.
export const TROUBLESHOOTING = [
  ['docs/TROUBLESHOOTING.md', 'en'],
  ['docs/pt/TROUBLESHOOTING.md', 'pt'],
];
export const GENERATED_LIST = 'tools/generated-files.json';
const AVISO = {
  pt: '<!-- GERADO por tools/render.mjs a partir de {{FONTE}} e do repos.conf. Não editar à mão: edita o template. -->\n\n',
  en: '<!-- GENERATED by tools/render.mjs from {{FONTE}} and repos.conf. Do not edit by hand: edit the template. -->\n\n',
};
AVISO.hi = AVISO.en;
AVISO.he = AVISO.en;

export function netHosts(vars) {
  const hosts = String(vars.NET_CHECK_HOSTS || '').split(/\s+/).filter(Boolean);
  for (const h of [vars.REPO_HOST, vars.MEMORY_HOST]) if (h && !hosts.includes(h)) hosts.push(h);
  return hosts;
}

export function fillTemplate(text, vars, name = 'template') {
  const unknown = new Set();
  const out = text.replace(/\{\{([A-Z][A-Z0-9_]*)\}\}/g, (all, k) => {
    if (vars[k] === undefined) {
      unknown.add(k);
      return all;
    }
    return String(vars[k]);
  });
  if (unknown.size) throw new Error(`${name}: marcadores desconhecidos: ${[...unknown].join(', ')}`);
  return out;
}

export function renderAll(root = KIT_ROOT, env = process.env) {
  const vars = derived(loadConf({ root, env }));
  vars.NET_HOSTS_LIST = netHosts(vars).map((h) => `- \`${h}\``).join('\n');
  const files = {};
  for (const [tmpl, dest, lingua] of TEMPLATES) {
    const src = readFileSync(join(root, tmpl), 'utf8');
    files[dest] = AVISO[lingua].replace('{{FONTE}}', tmpl) + fillTemplate(src, vars, tmpl);
  }
  for (const [dest, lingua] of TROUBLESHOOTING) {
    files[dest] = renderTroubleshooting(loadMessages(root, lingua), vars, { hosts: netHosts(vars), lingua });
  }
  return { vars, files };
}

function main(argv) {
  const { vars, files } = renderAll();
  if (argv.includes('--vars')) {
    for (const k of Object.keys(vars).sort()) console.log(`${k}=${vars[k]}`);
    return 0;
  }
  const list = { nota: 'Ficheiros gerados por tools/render.mjs. O tools/check-repo.mjs aceita URLs nestes ficheiros.', ficheiros: Object.keys(files).sort() };
  const all = { ...files, [GENERATED_LIST]: JSON.stringify(list, null, 2) + '\n' };
  if (argv.includes('--check')) {
    const stale = Object.entries(all).filter(([p, c]) => !existsSync(join(KIT_ROOT, p)) || readFileSync(join(KIT_ROOT, p), 'utf8') !== c);
    for (const [p] of stale) console.error(`desatualizado: ${p} (corre node tools/render.mjs)`);
    return stale.length ? 1 : 0;
  }
  for (const [p, c] of Object.entries(all)) {
    mkdirSync(dirname(join(KIT_ROOT, p)), { recursive: true });
    writeFileSync(join(KIT_ROOT, p), c);
    console.log(`gerado: ${p}`);
  }
  return 0;
}

if (process.argv[1] && process.argv[1].endsWith('render.mjs')) process.exitCode = main(process.argv.slice(2));
