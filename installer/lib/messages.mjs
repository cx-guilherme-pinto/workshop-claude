function bloco(cmds) {
  if (!cmds || !cmds.length) return '';
  return '\n```\n' + cmds.join('\n') + '\n```\n';
}

export function renderTroubleshooting(msgs, vars, { hosts = [], lingua = 'pt' } = {}) {
  const T = TXT[lingua];
  if (!T) throw new Error(`renderTroubleshooting: lingua desconhecida: ${lingua}`);
  const f = (t) => fillUpper(t, vars);
  const erros = msgs.erros;
  const codes = Object.keys(erros);
  const L = [];
  L.push(T.aviso);
  L.push('');
  L.push(T.titulo);
  L.push('');
  L.push(T.troca);
  L.push('');
  L.push(T.intro);
  L.push('');
  L.push(T.antes);
  L.push('');
  L.push(T.repetir);
  L.push(T.verificar(vars));
  L.push(T.doctor(vars));
  L.push(T.log);
  L.push(T.chave);
  L.push('');
  L.push(T.indice);
  L.push('');
  L.push(T.cabecalho);
  L.push('|---|---|---|');
  for (const c of codes) {
    const sos = erros[c].so === 'todos' ? ['mac', 'windows'] : [erros[c].so];
    const links = sos.map((so) => `[${SO_NOME[so]}](#${so}-${c.toLowerCase()})`).join(' · ');
    L.push(`| \`${c}\` | ${f(erros[c].titulo)} | ${links} |`);
  }
  L.push('');
  for (const so of ['mac', 'windows']) {
    L.push(`## ${SO_NOME[so]}`);
    L.push('');
    for (const c of codes) {
      const e = erros[c];
      if (e.so !== 'todos' && e.so !== so) continue;
      L.push(`<a id="${so}-${c.toLowerCase()}"></a>`);
      L.push('');
      L.push(`### ${c} · ${f(e.titulo)}`);
      L.push('');
      L.push(`${T.porque} ${f(e.causa)}`);
      L.push(T.fazer);
      for (const x of e.fazer) L.push(`  - ${f(x)}`);
      const cmds = (e[so] || []).map(f);
      if (cmds.length) {
        L.push('');
        L.push(T.comandos(cmds.length, SO_NOME[so]));
        L.push(bloco(cmds).trimEnd());
      }
      L.push('');
    }
  }
  L.push(T.dominios);
  L.push('');
  L.push(T.pedido);
  L.push('');
  for (const h of hosts) L.push(`- \`${h}\``);
  L.push('');
  L.push(T.proxies);
  L.push('');
  for (const l of T.proxyLinhas) L.push(l);
  L.push('');
  return L.join('\n') + '\n';
}
