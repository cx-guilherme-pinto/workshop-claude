const mmss = (m) => `${Math.floor(m)}:${String(Math.round((m % 1) * 60)).padStart(2, '0')}`;
const KEY = /^(Shift\+Tab|Esc|Enter|Ctrl\+)/;

// One command line → { label?, text }: "M8  /statusline …" becomes the label M8 and the command; a trailing
// "   (explanation)" becomes the label.
function parse(line) {
  let text = line.trim();
  let label = '';
  const m = /^(M\d+)\s+(.*)$/.exec(text);
  if (m) [label, text] = [m[1], m[2]];
  const e = /^(.*?)\s{2,}\((.*)\)$/.exec(text);
  if (e) [text, label] = [e[1], label ? `${label} · ${e[2]}` : e[2]];
  return { label, text };
}

export function commandsText(slides, lang, sub = (s) => s) {
  const t = T[lang] || T.en;
  const out = [t.titulo, '='.repeat(t.titulo.length), '', ...t.intro, t.gerado, ''];
  const [pre, ...os] = t.antesDeComecar;
  out.push('#'.repeat(72), `# ${pre}`, '#'.repeat(72), '');
  for (const [label, cmd] of os) out.push(`# ${label}`, sub(cmd), '');
  let clock = 0;
  slides.forEach((d, i) => {
    const start = clock;
    clock += d.min;
    const blocks = [];
    for (const c of d.comandos || []) {
      const lines = sub(c.cmd).split('\n').map((l) => l.trim()).filter(Boolean);
      const items = [];
      for (const l of lines) {
        const p = parse(l);
        if (KEY.test(p.text)) items.push(`# ${p.text.replace(/\s+/g, ' ')} (${t.tecla})`);
        else items.push(...(p.label ? [`# ${p.label}`] : []), p.text, '');
      }
      // the long command, for a laptop whose setup did not install the short ones yet
      const alt = (c.alt || []).flatMap((x) => (typeof x === 'string' ? [sub(x), ''] : [`# ${sub(x.rotulo)}`, sub(x.cmd), '']));
      blocks.push([`# ${sub(c.rotulo) || ''}`.trimEnd(), ...items, ...(alt.length ? [`# ${t.alt}`, ...alt] : [])]);
    }
    const pre = t.antes[`${d.fase}:${d.tipo}`];
    if (pre) blocks.push([`# ${pre[0]}`, ...pre.slice(1).flatMap((x) => [x, ''])]);
    // an option that is only a flag (--parallel 8) is not a command to paste: the next slide has the whole command
    const opts = (d.opcoes || []).filter((o) => !String(o.cmd).trim().startsWith('--'));
    if (opts.length) blocks.push([`# ${t.opcoes}`, ...opts.flatMap((o) => [`# ${o.titulo}`, sub(o.cmd), ''])]);
    const b = d.id && t.planoB[d.id];
    // after coming back, the slide's own request again
    if (b) blocks.push([`# ${b[0]}`, ...[...b.slice(1), sub(d.comandos?.[0]?.cmd || '')].filter(Boolean).flatMap((x) => [x, ''])]);
    if (!blocks.length) return;
    const head = `# [${mmss(start)}] ${t.slide} ${i + 1}${d.id ? ` · ${d.id}` : ''} · ${d.titulo}`;
    out.push('#'.repeat(72), head, '#'.repeat(72), '');
    for (const bl of blocks) {
      const [h, ...rest] = bl;
      if (h !== '#') out.push(h);
      out.push(...rest);
      if (rest.at(-1) !== '') out.push('');
    }
  });
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
